#!/usr/bin/env node
/**
 * Writes src/content/llms-source.generated.ts: the text of public/llms.txt as a
 * module constant. The /llms-full.txt route used to read that file with
 * node:fs, which fails on Cloudflare Workers because only files traced into the
 * bundle exist at runtime and public/ is served as static assets instead. Run
 * via prebuild.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'public/llms.txt';
const OUT = 'src/content/llms-source.generated.ts';
const body = readFileSync(SRC, 'utf8').trimEnd();

writeFileSync(
  OUT,
  `// Generated by scripts/gen-llms-source.mjs from ${SRC}. Do not edit.\n` +
    `export const LLMS_TXT_SOURCE: string = ${JSON.stringify(body)};\n`
);
console.log(`llms-source: wrote ${OUT} (${body.length} chars)`);
